"""Generates exports.h: forwards every export of System32\\dwmapi.dll (names + ordinals)."""
import re, subprocess, sys, os

dumpbin_out = sys.stdin.read()
lines = []
for m in re.finditer(r"^\s+(\d+)\s+(?:[0-9A-F]+\s+)?[0-9A-F]{8}\s+(\S+)\s*$", dumpbin_out, re.M):
    ordinal, name = int(m.group(1)), m.group(2)
    if name == "[NONAME]":
        lines.append(f'#pragma comment(linker, "/export:__ord{ordinal}=C:\\\\Windows\\\\System32\\\\dwmapi.#{ordinal},@{ordinal},NONAME")')
    else:
        lines.append(f'#pragma comment(linker, "/export:{name}=C:\\\\Windows\\\\System32\\\\dwmapi.{name},@{ordinal}")')

if len(lines) < 100:
    sys.exit(f"only parsed {len(lines)} exports, aborting")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "exports.h")
with open(out, "w") as f:
    f.write("// Generated by gen_exports.py from C:\\Windows\\System32\\dwmapi.dll\n#pragma once\n")
    f.write("\n".join(lines) + "\n")
print(f"wrote {len(lines)} exports to {out}")

